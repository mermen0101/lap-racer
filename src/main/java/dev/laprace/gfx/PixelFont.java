package dev.laprace.gfx;

import java.util.HashMap;
import java.util.Map;

/** A tiny 5x7 font for the numbers and labels baked into the dials. */
final class PixelFont {
	private static final Map<Character, String[]> G = new HashMap<>();
	private static final String[] BLANK = {"   ", "   ", "   ", "   ", "   ", "   ", "   "};

	static {
		put('0', " ### ", "#   #", "#  ##", "# # #", "##  #", "#   #", " ### ");
		put('1', "  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### ");
		put('2', " ### ", "#   #", "    #", "   # ", "  #  ", " #   ", "#####");
		put('3', "#####", "   # ", "  #  ", "   # ", "    #", "#   #", " ### ");
		put('4', "   # ", "  ## ", " # # ", "#  # ", "#####", "   # ", "   # ");
		put('5', "#####", "#    ", "#### ", "    #", "    #", "#   #", " ### ");
		put('6', "  ## ", " #   ", "#    ", "#### ", "#   #", "#   #", " ### ");
		put('7', "#####", "    #", "   # ", "  #  ", " #   ", " #   ", " #   ");
		put('8', " ### ", "#   #", "#   #", " ### ", "#   #", "#   #", " ### ");
		put('9', " ### ", "#   #", "#   #", " ####", "    #", "   # ", " ##  ");
		put('E', "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####");
		put('F', "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    ");
		put('k', "#    ", "#    ", "#  # ", "# #  ", "##   ", "# #  ", "#  # ");
		put('m', "     ", "     ", "## # ", "# # #", "# # #", "# # #", "# # #");
		put('h', "#    ", "#    ", "# ## ", "##  #", "#   #", "#   #", "#   #");
		put('p', "     ", "     ", "#### ", "#   #", "#### ", "#    ", "#    ");
		put('r', "     ", "     ", "# ## ", "##  #", "#    ", "#    ", "#    ");
		put('x', "     ", "     ", "#   #", " # # ", "  #  ", " # # ", "#   #");
		put('s', "     ", "     ", " ####", "#    ", " ### ", "    #", "#### ");
		put('t', " #   ", " #   ", "#### ", " #   ", " #   ", " #  #", "  ## ");
		put('d', "    #", "    #", " ## #", "#  ##", "#   #", "#   #", " ####");
		put('i', "  #  ", "     ", " ##  ", "  #  ", "  #  ", "  #  ", " ### ");
		put('f', "  ## ", " #  #", " #   ", "###  ", " #   ", " #   ", " #   ");
		put('/',"    #", "    #", "   # ", "  #  ", " #   ", "#    ", "#    ");
		put('.', "     ", "     ", "     ", "     ", "     ", " ##  ", " ##  ");
		put('-', "     ", "     ", "     ", "#####", "     ", "     ", "     ");
		put('°', " ##  ", "#  # ", " ##  ", "     ", "     ", "     ", "     ");
	}

	private PixelFont() {
	}

	private static void put(char c, String... rows) {
		G.put(c, rows);
	}

	static String[] glyph(char c) {
		return G.getOrDefault(c, BLANK);
	}

	static int advance(char c) {
		return c == ' ' ? 3 : c == '.' ? 4 : 6;
	}

	static int width(String s) {
		int w = 0;
		for (int i = 0; i < s.length(); i++) {
			w += advance(s.charAt(i));
		}
		return Math.max(0, w - 1);
	}
}
